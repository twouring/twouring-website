// 洞察列表互動驗證：篩選、載入更多、zh-only 文章的語言切換
import { createRequire } from 'node:module';
import { globSync } from 'node:fs';
const require = createRequire('/opt/gstack/node_modules/');
const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:4329';
const exe = globSync('/opt/gstack/browsers/chromium_headless_shell-*/chrome-headless-shell-linux64/chrome-headless-shell').sort().at(-1);
const b = await chromium.launch({ executablePath: exe });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
await p.goto(base + '/insights/', { waitUntil: 'networkidle' });
const vis = () => p.evaluate(() => [...document.querySelectorAll('.rows li')].filter((x) => !x.hidden).length);
const r = {};
r.total = await p.evaluate(() => document.querySelectorAll('.rows li').length + 1);
r.count = await p.evaluate(() => document.querySelector('.count')?.textContent);
r.oldest = await p.evaluate(() => [...document.querySelectorAll('.rows .meta span:first-child')].at(-1)?.textContent);
r.featured = await p.evaluate(() => document.querySelector('.feature h2')?.textContent);
r.initial = await vis();
await p.click('.more'); r.afterMore = await vis();
const chips = await p.$$('.chip'); r.chips = chips.length;
await chips[1].click(); r.filterName = await chips[1].textContent(); r.filtered = await vis();
r.filterOk = await p.evaluate((n) => [...document.querySelectorAll('.rows li')].filter((x) => !x.hidden).every((x) => x.dataset.cat === n), r.filterName);
await chips[0].click(); r.backAll = await vis();
await p.goto(base + '/insights/a-saas-sla-without-empty-promises/', { waitUntil: 'networkidle' });
r.zhOnlyLang = await p.evaluate(() => [...document.querySelectorAll('.lang-switch')].map((a) => a.getAttribute('href')));
r.hreflang = await p.evaluate(() => [...document.querySelectorAll('link[rel=alternate][hreflang]')].map((l) => l.hreflang));
r.related = await p.evaluate(() => document.querySelectorAll('.rel').length);
await p.screenshot({ path: '/workspace/local/_scratch/insight-shots/zh-only-art-1280.png' });
const en = await (await b.newPage()).goto(base + '/en/insights/a-saas-sla-without-empty-promises/');
r.enStatus = en.status();
console.log(JSON.stringify(r, null, 1));
await b.close();
